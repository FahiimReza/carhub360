// Test script to verify PDF export functionality
// Run this in the browser console after loading the admin page

console.log('🧪 Testing PDF Export Functionality...');

// Test 1: Check if jsPDF library is loaded
function testJSPDFLoaded() {
    try {
        if (typeof window.jspdf !== 'undefined' && typeof window.jspdf.jsPDF !== 'undefined') {
            console.log('✅ jsPDF library loaded successfully');
            return true;
        } else {
            console.error('❌ jsPDF library not found');
            console.log('   Make sure the jsPDF CDN links are added to admin.html');
            return false;
        }
    } catch (error) {
        console.error('❌ Error loading jsPDF:', error);
        return false;
    }
}

// Test 2: Check if autoTable plugin is loaded
function testAutoTableLoaded() {
    try {
        if (typeof window.jspdf !== 'undefined') {
            const { jsPDF } = window.jspdf;
            const doc = new jsPDF();
            
            if (typeof doc.autoTable !== 'undefined') {
                console.log('✅ jsPDF AutoTable plugin loaded successfully');
                return true;
            } else {
                console.warn('⚠️ jsPDF AutoTable plugin not found, using fallback method');
                return false;
            }
        } else {
            console.error('❌ jsPDF not loaded');
            return false;
        }
    } catch (error) {
        console.error('❌ Error testing AutoTable:', error);
        return false;
    }
}

// Test 3: Test basic PDF generation
function testPDFGeneration() {
    try {
        if (typeof window.jspdf === 'undefined') {
            console.error('❌ jsPDF not available for testing');
            return false;
        }
        
        const { jsPDF } = window.jspdf;
        const doc = new jsPDF();
        
        // Add some test content
        doc.setFontSize(16);
        doc.text('PDF Export Test', 20, 20);
        doc.setFontSize(12);
        doc.text('This is a test PDF generated by CarHub360 Export System', 20, 30);
        
        // Generate PDF blob
        const pdfBlob = doc.output('blob');
        
        if (pdfBlob instanceof Blob && pdfBlob.type === 'application/pdf') {
            console.log('✅ PDF generation test successful');
            console.log(`   Generated PDF size: ${pdfBlob.size} bytes`);
            return true;
        } else {
            console.error('❌ PDF generation failed');
            return false;
        }
    } catch (error) {
        console.error('❌ Error testing PDF generation:', error);
        return false;
    }
}

// Test 4: Test CSV to PDF conversion
